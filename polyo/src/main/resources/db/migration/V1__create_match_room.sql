CREATE TABLE match_room (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_name    VARCHAR(30) NOT NULL,
    host_user_id VARCHAR(64) NOT NULL,
    is_private   BOOLEAN     NOT NULL,
    entry_code   VARCHAR(8)  NOT NULL UNIQUE,
    status       VARCHAR(20) NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_match_room_status_created_at ON match_room (status, created_at DESC, id DESC);

CREATE TABLE match_room_member (
    room_id    BIGINT      NOT NULL REFERENCES match_room (id) ON DELETE CASCADE,
    join_order INTEGER     NOT NULL,
    user_id    VARCHAR(64) NOT NULL,
    nickname   VARCHAR(50) NOT NULL,
    PRIMARY KEY (room_id, join_order),
    UNIQUE (room_id, user_id)
);
